// Generates the dashboard token CSS files from design-tokens.json (the single source of truth):
//   dashboard/src/ui/tokens.css                       <- dashboard.foundation                (--ku-*)
//   dashboard/src/modules/superadmin/shared/tokens.css <- dashboard.colors/compound/terminal  (--db-*)
//                                                        + dashboard.superadmin               (--sa-*)
// Never edit the generated tokens.css files by hand.
// Usage: node scripts/build-ui-tokens.js          (write)
//        node scripts/build-ui-tokens.js --check  (fail when a tokens.css is out of date; used by lint:tokens)
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'design-tokens.json'), 'utf8'));
const d = tokens.dashboard || {};
const f = d.foundation;
if (!f) {
  console.error('design-tokens.json: dashboard.foundation is missing');
  process.exit(1);
}
for (const key of ['colors', 'compound', 'terminal', 'superadmin']) {
  if (!d[key]) {
    console.error(`design-tokens.json: dashboard.${key} is missing`);
    process.exit(1);
  }
}

// --- src/ui/tokens.css (--ku-*) ---------------------------------------------------------------
const kuLines = [];
for (const [group, values] of Object.entries(f)) {
  if (group.startsWith('_')) continue;
  kuLines.push(`  /* ${group} */`);
  for (const [k, v] of Object.entries(values)) kuLines.push(`  --ku-${group === 'color' ? '' : group + '-'}${k}: ${v};`);
  kuLines.push('');
}
const kuCss = `/* GENERATED by scripts/build-ui-tokens.js from design-tokens.json (dashboard.foundation). Do not edit. */
:root {
${kuLines.join('\n').trimEnd()}
}
`;

// --- modules/superadmin/shared/tokens.css (--db-*, --sa-*) -------------------------------------
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
// dashboard.colors keys whose CSS var name is shorter than the kebab-cased key (names already in use).
const DB_ALIAS = {
  sidebarBackground: 'sidebar-bg',
  pageBackground: 'page-bg',
  cardBackground: 'card-bg',
  positiveIndicator: 'positive',
  negativeIndicator: 'negative',
};
const section = (title, entries) => {
  const out = [`  /* ${title} */`];
  for (const [name, v] of entries) out.push(`  ${name}: ${v};`);
  out.push('');
  return out;
};
const values = (obj) => Object.entries(obj).filter(([k]) => !k.startsWith('_'));
const dbLines = [
  ...section('dashboard.colors', values(d.colors).map(([k, v]) => [`--db-${DB_ALIAS[k] || kebab(k)}`, v])),
  ...section('dashboard.compound', values(d.compound).map(([k, v]) => [`--db-${kebab(k)}`, v])),
  ...section('dashboard.terminal', values(d.terminal).map(([k, v]) => [`--db-term-${kebab(k)}`, v])),
  ...section('dashboard.superadmin', values(d.superadmin).map(([k, v]) => [`--sa-${kebab(k)}`, v])),
];
const dbCss = `/* GENERATED by scripts/build-ui-tokens.js from design-tokens.json (dashboard.colors, compound, terminal, superadmin). Do not edit. */
:root {
${dbLines.join('\n').trimEnd()}
}
`;

const targets = [
  [path.join(root, 'dashboard', 'src', 'ui', 'tokens.css'), kuCss],
  [path.join(root, 'dashboard', 'src', 'modules', 'superadmin', 'shared', 'tokens.css'), dbCss],
];

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [target, css] of targets) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== css) {
      console.error(`${path.relative(root, target)} is out of date: run node scripts/build-ui-tokens.js`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log('ui tokens up to date');
} else {
  for (const [target, css] of targets) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, css);
    console.log('wrote ' + path.relative(root, target));
  }
}
