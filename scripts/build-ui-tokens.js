// Generates dashboard/src/ui/tokens.css from design-tokens.json -> dashboard.foundation.
// design-tokens.json is the single source of truth; never edit tokens.css by hand.
// Usage: node scripts/build-ui-tokens.js          (write)
//        node scripts/build-ui-tokens.js --check  (fail when tokens.css is out of date; used by lint:tokens)
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'design-tokens.json'), 'utf8'));
const f = tokens.dashboard && tokens.dashboard.foundation;
if (!f) {
  console.error('design-tokens.json: dashboard.foundation is missing');
  process.exit(1);
}

const lines = [];
for (const [group, values] of Object.entries(f)) {
  if (group.startsWith('_')) continue;
  lines.push(`  /* ${group} */`);
  for (const [k, v] of Object.entries(values)) lines.push(`  --ku-${group === 'color' ? '' : group + '-'}${k}: ${v};`);
  lines.push('');
}
const css = `/* GENERATED by scripts/build-ui-tokens.js from design-tokens.json (dashboard.foundation). Do not edit. */
:root {
${lines.join('\n').trimEnd()}
}
`;
const target = path.join(root, 'dashboard', 'src', 'ui', 'tokens.css');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== css) {
    console.error('dashboard/src/ui/tokens.css is out of date: run node scripts/build-ui-tokens.js');
    process.exit(1);
  }
  console.log('ui tokens up to date');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, css);
  console.log('wrote ' + path.relative(root, target));
}
