// Generates web/app/typography.css from design-tokens.json (typography.fontSize, typography.roles, spacing).
//   --tw-fs-<size>        font sizes of the scale
//   --tw-type-<role>      a complete `font` shorthand for a role: weight size/line family
// Use a role as:   font: var(--tw-type-row-title);
// Never edit web/app/typography.css by hand.
// Usage: node scripts/build-type-tokens.js          (write)
//        node scripts/build-type-tokens.js --check  (fail when the file is out of date)
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'design-tokens.json'), 'utf8'));
const t = tokens.typography;
if (!t || !t.roles || !t.fontSize) {
  console.error('design-tokens.json: typography.fontSize and typography.roles are required');
  process.exit(1);
}

const FAMILY = { heading: 'var(--tw-font-heading)', body: 'var(--tw-font-body)' };
const entries = (o) => Object.entries(o).filter(([k]) => !k.startsWith('_'));
const problems = [];

const lines = ['  /* user text scale: 1 normally; a larger value scales every role (accessibility hook) */', '  --tw-type-scale: 1;', '', '  /* font sizes */'];
for (const [k, v] of entries(t.fontSize)) lines.push(`  --tw-fs-${k}: calc(${v} * var(--tw-type-scale));`);
lines.push('', '  /* spacing scale */');
for (const [k, v] of entries(tokens.spacing || {})) lines.push(`  --tw-space-${k}: ${v};`);
lines.push('', '  /* radius */');
for (const [k, v] of entries(tokens.radius || {})) lines.push(`  --tw-radius-${k}: ${v};`);
lines.push('', '  /* roles: weight size/line family */');
for (const [name, r] of entries(t.roles)) {
  const weight = t.fontWeight[r.weight];
  const size = t.fontSize[r.size];
  const line = t.lineHeight[r.size];
  const family = FAMILY[r.family];
  if (!weight || !size || !line || !family) {
    problems.push(`role "${name}": unknown weight/size/line/family (${r.weight}, ${r.size}, ${r.family})`);
    continue;
  }
  lines.push(`  --tw-type-${name}: ${weight} calc(${size} * var(--tw-type-scale))/calc(${line} * var(--tw-type-scale)) ${family};`);
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const css = `/* GENERATED by scripts/build-type-tokens.js from design-tokens.json (typography). Do not edit. */
:root {
${lines.join('\n')}
}
`;

const out = path.join(root, 'web', 'app', 'typography.css');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== css) {
    console.error('web/app/typography.css is out of date: run node scripts/build-type-tokens.js');
    process.exit(1);
  }
  console.log('Type tokens are up to date.');
} else {
  fs.writeFileSync(out, css);
  console.log('wrote web/app/typography.css');
}
